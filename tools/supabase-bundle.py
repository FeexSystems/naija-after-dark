#!/usr/bin/env python3
"""
Bundle supabase/migrations/*.sql into one ordered, paste-ready file.

The repo has no `supabase` CLI wired into CI and no local Docker, so applying the
schema to a fresh Supabase project is done by pasting one file into the SQL editor.
This keeps that file in lockstep with the migrations instead of hand-maintained.

Usage:
    python tools/supabase-bundle.py            # write supabase/apply_all.sql
    python tools/supabase-bundle.py --check    # fail if apply_all.sql is stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIGRATIONS = ROOT / "supabase" / "migrations"
OUTPUT = ROOT / "supabase" / "apply_all.sql"

HEADER = """-- ===========================================================================
-- NAAD - complete schema bundle (GENERATED - do not edit by hand)
--
-- Generated by tools/supabase-bundle.py from supabase/migrations/*.sql.
-- Regenerate with:  python tools/supabase-bundle.py
--
-- Paste this whole file into a fresh Supabase project's SQL editor
-- (Dashboard -> SQL Editor -> New query -> Run). Then follow
-- docs/SUPABASE_RESTORE_RUNBOOK.md to point the Unity client at the project.
--
-- Included migrations:
"""


def migration_files() -> list[Path]:
    files = sorted(MIGRATIONS.glob("*.sql"))
    if not files:
        sys.exit(f"error: no .sql files in {MIGRATIONS}")
    return files


def build() -> str:
    files = migration_files()
    parts = [HEADER]
    for f in files:
        parts.append(f"--   {f.name}\n")
    parts.append("-- ===========================================================================\n\n")

    for f in files:
        body = f.read_text(encoding="utf-8").rstrip()
        parts.append(
            "\n-- " + "=" * 73 + f"\n-- {f.name}\n-- " + "=" * 73 + "\n\n"
        )
        parts.append(body + "\n")

    return "".join(parts)


def main() -> int:
    generated = build()

    if "--check" in sys.argv:
        if not OUTPUT.exists():
            print(f"STALE: {OUTPUT.name} does not exist; run tools/supabase-bundle.py")
            return 1
        if OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"STALE: {OUTPUT.name} differs from the migrations.")
            print("Re-run: python tools/supabase-bundle.py")
            return 1
        print(f"OK: {OUTPUT.name} is in sync with {len(migration_files())} migrations.")
        return 0

    OUTPUT.write_text(generated, encoding="utf-8")
    n = len(migration_files())
    lines = generated.count("\n")
    funcs = len(re.findall(r"create\s+or\s+replace\s+function", generated, re.I))
    print(f"wrote {OUTPUT.relative_to(ROOT)} - {n} migrations, {lines} lines, {funcs} function definitions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
